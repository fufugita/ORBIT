#!/usr/bin/env bash
# Isolated release-profile binary workflow test.
# This copies a locally built binary into a temporary directory and uses fresh homes;
# it does not exercise the managed installer or establish release evidence.
set -euo pipefail

ROOT="$(realpath -e -- "$(dirname "${BASH_SOURCE[0]}")/..")"
if [[ $# -ne 1 || "$1" != /* ]]; then
  printf 'Usage: %s /absolute/new/output-directory\n' "$0" >&2
  exit 2
fi

REQUESTED_OUTPUT="$1"
OUTPUT_PARENT="$(realpath -e -- "$(dirname -- "$REQUESTED_OUTPUT")")" || {
  printf 'Output parent must already exist: %s\n' "$(dirname -- "$REQUESTED_OUTPUT")" >&2
  exit 2
}
OUTPUT_NAME="$(basename -- "$REQUESTED_OUTPUT")"
OUTPUT_DIR="$OUTPUT_PARENT/$OUTPUT_NAME"
if [[ -e "$OUTPUT_DIR" || -L "$OUTPUT_DIR" ]]; then
  printf 'Output destination already exists: %s\n' "$OUTPUT_DIR" >&2
  exit 2
fi
case "$OUTPUT_DIR" in
  "$ROOT"|"$ROOT/"*)
    printf 'Output destination must be outside the repository: %s\n' "$OUTPUT_DIR" >&2
    exit 2
    ;;
esac
TMP_ROOT="${TMPDIR:-/tmp}"
if [[ "$TMP_ROOT" != /* ]]; then
  printf 'TMPDIR must be an absolute path outside the repository: %s\n' "$TMP_ROOT" >&2
  exit 2
fi
TMP_ROOT="$(realpath -e -- "$TMP_ROOT")" || {
  printf 'TMPDIR must already exist: %s\n' "${TMPDIR:-/tmp}" >&2
  exit 2
}
case "$TMP_ROOT" in
  "$ROOT"|"$ROOT/"*)
    printf 'TMPDIR must be outside the repository: %s\n' "$TMP_ROOT" >&2
    exit 2
    ;;
esac

# All run output and build paths are external; path checks above run first.
WORK="$(mktemp -d "$TMP_ROOT/orbit-clean-machine.XXXXXXXX")"
HOME1="$WORK/orbit-home"
HOME2="$WORK/orbit-restored"
ARCHIVE="$WORK/backup.age"
BIN="$WORK/bin/orbit"
TRANSCRIPT="$OUTPUT_DIR/demo-transcript.md"
SUMMARY="$OUTPUT_DIR/e2e-summary.json"

cleanup() { rm -rf -- "$WORK"; }
trap cleanup EXIT

mkdir -- "$OUTPUT_DIR"
mkdir -p "$WORK/bin"

run() {
  local label="$1"; shift
  printf '\n### %s\n\n```console\n$ %q' "$label" "$1" >> "$TRANSCRIPT"
  for arg in "${@:2}"; do printf ' %q' "$arg" >> "$TRANSCRIPT"; done
  printf '\n' >> "$TRANSCRIPT"
  "$@" | tee -a "$TRANSCRIPT"
  printf '```\n' >> "$TRANSCRIPT"
}

cat > "$TRANSCRIPT" <<'HDR'
# ORBIT isolated release-binary workflow transcript

Generated by `scripts/e2e-clean-machine.sh`. This records command output only;
it is not a managed-install or release-evidence attestation.
HDR

# 1. Build in release profile and copy to an isolated temporary directory.
printf '\n## Environment\n\n- Workspace: isolated temp directory\n- ORBIT_HOME: fresh\n- Binary: copied from release build\n' >> "$TRANSCRIPT"
CARGO_TARGET_DIR="$WORK/cargo-target" cargo build --manifest-path "$ROOT/Cargo.toml" --offline --locked --release -p orbit-cli --bin orbit -j1
cp "$WORK/cargo-target/release/orbit" "$BIN"
chmod 0755 "$BIN"
run "1. Check version report and evidence availability" "$BIN" version --evidence --home "$HOME1"

# 2. Initialize trust (local root + PIB + Ledger).
run "2. Initialize trust" "$BIN" init --home "$HOME1"

# 3. Run example.
run "3. Run example" "$BIN" run example --auto --home "$HOME1"

# 4. Cancel it.
run "4. Cancel" "$BIN" cancel --session session-example --home "$HOME1"

# 5. Verify original Ledger.
run "5. Verify Ledger" "$BIN" verify-ledger --home "$HOME1"

# 6. Inspect a dry replay.
run "6. Replay dry" "$BIN" replay session-example --dry --home "$HOME1"

# 7. Export encrypted local archive.
run "7. Export" "$BIN" export session-example --to "$ARCHIVE" --home "$HOME1"

# 8. Restore into a fresh namespace.
run "8. Restore" "$BIN" restore "$ARCHIVE" --into "$HOME2" --home "$HOME1"

# 9. Verify restored Ledger.
run "9. Verify restored Ledger" "$BIN" verify-ledger --home "$HOME2"

cat > "$SUMMARY" <<JSON
{
  "schema": "orbit.isolated-workflow-summary/v1",
  "test_scope": "isolated release-profile binary workflow; no managed installer or release-evidence claim",
  "result": "all_commands_succeeded",
  "steps": [
    "build_release_profile_binary", "copy_binary_to_isolated_path", "initialize_trust", "run_example", "cancel", "verify_ledger",
    "replay_dry", "export_encrypted", "restore_fresh_namespace", "verify_restored"
  ]
}
JSON

printf '\nIsolated release-binary workflow: completed\n' | tee -a "$TRANSCRIPT"
printf 'Transcript: %s\nSummary: %s\n' "$TRANSCRIPT" "$SUMMARY"
